"""Generate conservative bobina profiles from escpos-printer-db (receipt-print-hq, CC BY 4.0).

Usage: python tools/import_profiles.py DIR_WITH_YML [--out src/bobina/profiles]

The database gives model facts (paper width in dots, dpi, columns of font A, native QR). What it cannot give is
what bobina measures on paper (tear bar, firmware quirks, glyphs the internal font prints), so every generated
profile is `measured = false` and conservative:
- native text in ASCII only (bobina sends UTF-8; other printers need code pages): accents and symbols go raster;
- native sizes up to 2x, barcodes raster, QR native only when the database says the printer has it;
- safe mode on (white raster rows after images), tear bar assumed at 5 mm: run bobina calibrate tear and feed.
Skipped: generic profiles, Star command printers, printers without raster images, unknown width or dpi.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path

import yaml

GENERIC = {"default", "safe", "simple"}
HEADER = """# Imported from escpos-printer-db, profile "{key}" (receipt-print-hq, CC BY 4.0,
# https://github.com/receipt-print-hq/escpos-printer-db). Model facts only: NOT measured on paper.
# Generated by tools/import_profiles.py; edit the generator, not this file. Calibrate with:
#   bobina calibrate tear   and   bobina calibrate feed
"""


def load_all(src: Path) -> dict:
    out = {}
    for f in sorted(src.glob("*.yml")):
        out.update(yaml.safe_load(f.read_text(encoding="utf-8")) or {})
    return out


REPLACE = {"codePages"}  # a child's code pages are the ones it has, not the parent's plus its own


def merge(a: dict, b: dict) -> dict:
    out = dict(a)
    for k, v in b.items():
        nested = isinstance(v, dict) and isinstance(out.get(k), dict) and k not in REPLACE
        out[k] = merge(out[k], v) if nested else v
    return out


PREFERRED = ["cp860", "cp850", "cp858", "cp1252", "cp437", "iso8859_15"]  # Portuguese first, then Latin, then the rest
NATIVE_BARCODES = ["upca", "ean13", "ean8", "code39", "codabar", "code93", "code128"]  # not itf/upce: failed on MTP-II


# Pages bobina can send as they are: one byte per character, written left to right. Not CP932 (on these printers
# page 1 is half-width Katakana, while Python's cp932 is multi-byte Shift-JIS), not Arabic or Hebrew pages (the
# printer would print them left to right, unshaped). Anything else stays raster.
SAFE_CODECS = {
    "cp437", "cp850", "cp852", "cp855", "cp857", "cp858", "cp860", "cp861", "cp863", "cp865", "cp866", "cp869",
    "cp737", "cp775", "cp1250", "cp1251", "cp1252", "cp1253", "cp1254", "cp1257", "iso8859_2", "iso8859_7",
    "iso8859_15",
}  # fmt: skip


def codec(name: str) -> str | None:
    """escpos-printer-db's page name -> a Python codec bobina may use (SAFE_CODECS), or None."""
    import codecs

    n = str(name).lower().replace("iso_8859-", "iso8859_").replace("-", "_")
    try:
        c = codecs.lookup(n).name.replace("-", "_") if n != "unknown" else None
    except LookupError:
        return None
    return c if c in SAFE_CODECS else None


def code_pages(p: dict) -> dict:
    found = {}
    for number, name in sorted((p.get("codePages") or {}).items(), key=lambda kv: int(kv[0])):
        c = codec(name)
        if c and c not in found:
            found[c] = int(number)
    order = [c for c in PREFERRED if c in found] + [c for c in found if c not in PREFERRED]
    return {c: found[c] for c in order}


def resolve(key: str, db: dict, seen=()) -> dict:
    if key in seen:
        raise ValueError(f"inheritance loop at {key}")
    p = db[key]
    parent = p.get("inherits")
    return merge(resolve(parent, db, (*seen, key)), p) if parent else p


def known(v) -> bool:
    return v not in (None, "Unknown", "")


def slug(vendor: str, model: str) -> str:
    v = re.sub(r"[^a-z0-9]+", "-", vendor.lower()).strip("-").split("-")[0]
    m = re.sub(r"[^a-z0-9]+", "-", model.lower()).strip("-")
    return m if m.startswith(v) else f"{v}-{m}"


def why_skipped(key: str, p: dict) -> str | None:
    feats, media = p.get("features", {}), p.get("media", {})
    width, dpi = (media.get("width") or {}).get("pixels"), media.get("dpi")
    if key in GENERIC:
        return "generic profile"
    if feats.get("starCommands"):
        return "Star commands, not ESC/POS"
    if not feats.get("bitImageRaster"):
        return "no raster images (GS v 0)"
    if not (known(width) and known(dpi)):
        return "paper width or dpi unknown"
    if int(width) < 200:
        return "too narrow for a label (dot-matrix display or slip)"
    return None


def toml_profile(key: str, p: dict) -> tuple[str, str]:
    media, feats = p["media"], p.get("features", {})
    width, dpi = int(media["width"]["pixels"]), int(media["dpi"])
    mm = dpi / 25.4
    cols = (p.get("fonts", {}).get(0) or {}).get("columns")
    cols = int(cols) if known(cols) and int(cols) else width // 12
    cell_w = math.ceil(width / cols)  # rounded up: bobina never lays out more characters than the printer has
    if not 8 <= cell_w <= 16:  # the database's "Font A" columns are sometimes another font (NT-80-V-UL: 12)
        cell_w, cols = 12, width // 12
    printable_mm = width / mm
    paper_mm = 58 if printable_mm <= 56 else 80 if printable_mm <= 80.5 else 112  # the standard roll widths
    vendor, name = p.get("vendor", "Unknown"), p.get("name", key)
    pid = slug(vendor, key)
    full = name if vendor.lower() in name.lower() else f"{vendor} {name}"
    if key.lower() not in full.lower():  # RP-F10-58mm and RP-F10-80mm share the name "RP-F10"
        full = f"{full} ({key})"
    qr = "true" if feats.get("qrCode") is True else "false"
    pages = code_pages(p)
    cutter = "partial" if feats.get("paperPartCut") else "full" if feats.get("paperFullCut") else "none"
    barcodes = NATIVE_BARCODES if feats.get("barcodeB") else []
    pages_toml = "\n".join(f"{c} = {n}" for c, n in pages.items())
    enc_note = "⚠ code pages not tested on paper (docs/TESTED.md)" if pages else "no usable code page: accents raster"
    body = f"""{HEADER.format(key=key)}
id = {json.dumps(pid)}
name = {json.dumps(full, ensure_ascii=False)}
source = {json.dumps(f"escpos-printer-db: {key} (CC BY 4.0)")}
measured = false
evidence = "not measured on paper: model facts from escpos-printer-db; bobina's safe mode is on"
width_dots = {width}          # {printable_mm:.0f} mm printable
dpi = {dpi}
paper_mm = {paper_mm}
command_set = "escpos"
encoding = "{"codepage" if pages else "ascii"}"     # {enc_note}
cutter = "{cutter}"          # from the database; ⚠ not tested on paper

[margins]
top_dots = {round(3 * mm)}
block_gap_dots = {round(1.5 * mm)}
tear_dots = {round(5 * mm)}            # assumed 5 mm: bobina calibrate tear measures it
feed_after_dots = {round(11 * mm)}      # tear bar + 6 mm to spare

[transport]
chunk_bytes = 4096
pause_s = 0.0
band_rows = 64
print_mm_per_s = 40

[escpos]
blank_rows_after_raster = true  # safe until bobina calibrate feed says ESC J works after images

[native]
cell = [{cell_w}, 24]           # font A, {cols} columns ({width} dots / {cols}, rounded up)
line_gap_dots = 6
emulation_font = "spleen-12x24.otf"   # a 12-dot font: with a wider cell the preview spacing is approximate
scales_ok = [1, 2]
glyph_ranges = [[0x20, 0x7E]]   # without code pages: ASCII native, everything else raster

[native.sizes]
small = [1, 1]
normal = [1, 1]
large = [2, 2]
title = [2, 2]
huge = [2, 2]

[native.headings]
h1 = {{ scale = [2, 2], bold = true }}
h2 = {{ scale = [1, 2], bold = true }}
h3 = {{ scale = [1, 1], bold = true }}

[qr]
native = {qr}            # from the database; raster QR otherwise
default_module = 4
min_module_native = 3
min_module_raster = 4
default_ecc = "M"

[barcode]
native = {json.dumps(barcodes)}  # from the database (barcodeB); ⚠ not tested on paper
min_module = 2
default_module = 2
default_height = {round(10 * mm)}
min_module_feed = 4
quiet_modules = 10

[raster]
min_stroke_dots = 2
min_gap_dots = 2
min_text_px = 12
invert_min_px = 20
invert_margin_dots = 4

[image]
dither = "floyd-steinberg"
gamma = 1.8

[preview]
calibrated = false

[preview.realistic]
spread_px = 0.6
gain = 1.25
ink = [38, 36, 42]
paper = [247, 245, 239]
fade_dots = 0
fade_strength = 0.0
scale = 2
""" + (f"\n[codepages]               # codec = ESC t number, preferred first\n{pages_toml}\n" if pages else "")
    return pid, body


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("src", type=Path, help="folder with the .yml files of escpos-printer-db data/profile")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "src/bobina/profiles")
    a = ap.parse_args(argv)
    db = load_all(a.src)
    written, skipped, owner = [], [], {}
    for key in sorted(db):
        p = resolve(key, db)
        reason = why_skipped(key, p)
        if reason:
            skipped.append((key, reason))
            continue
        pid, body = toml_profile(key, p)
        if pid in owner:
            raise SystemExit(f"{key} and {owner[pid]} both become {pid}.toml: give one of them another id")
        owner[pid] = key
        target = a.out / f"{pid}.toml"
        if target.exists() and "measured = false" not in target.read_text(encoding="utf-8"):
            skipped.append((key, f"{target.name} is a measured profile: not overwritten"))
            continue
        target.write_text(body, encoding="utf-8")
        written.append(pid)
    print(f"wrote {len(written)} profiles: {', '.join(written)}")
    for key, reason in skipped:
        print(f"skipped {key}: {reason}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
