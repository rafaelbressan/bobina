"""Write llms-full.txt: the docs an agent needs, in one file (llmstxt.org). tests/test_llms.py checks it is current.

Usage: python tools/gen_llms_full.py
"""

from __future__ import annotations

import posixpath
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARTS = [
    "README.md",
    "docs/agents.md",
    "docs/CLI.md",
    "docs/FORMAT.md",
    "docs/guides/batch-printing.md",
    "docs/guides/templates.md",
    "docs/SECURITY.md",
    "docs/INSTALL.md",
]
# Sections an agent does not need to use bobina (how it was decided, how the help is laid out, the change log, plans
# for a server that does not exist yet): they stay in the docs and on the site; llms-full.txt names where they are.
SKIP = {
    "docs/CLI.md": ("## Decided", "## Help layout"),
    "docs/FORMAT.md": ("## 10. Conformance", "## Appendix B — changes"),
    "docs/SECURITY.md": ("## Requirements before a print server or chat bot exists", "## Open"),
}
LINK = re.compile(r"(\]\()([^)\s]+)(\))")


def _without(text: str, rel: str) -> str:
    """The doc without its SKIP sections (a heading up to the next heading of the same level)."""
    for heading in SKIP.get(rel, ()):
        start = text.find(heading + "\n")
        if start < 0:
            raise SystemExit(f"{rel}: section '{heading}' not found (update SKIP in tools/gen_llms_full.py)")
        nxt = text.find("\n## ", start + len(heading))
        end = len(text) if nxt < 0 else nxt + 1
        text = text[:start] + f"<!-- '{heading[3:]}' left out here: see {rel} -->\n\n" + text[end:]
    return text


def _rebase(text: str, rel: str) -> str:
    """Links relative to a doc in docs/ become relative to the root, where llms-full.txt lives."""
    folder = posixpath.dirname(rel)

    def fix(m):
        target = m.group(2)
        if not folder or re.match(r"[a-z]+:|#|/", target):
            return m.group(0)
        path, _, anchor = target.partition("#")
        rebased = posixpath.normpath(posixpath.join(folder, path))
        if not (ROOT / rebased).exists():  # a syntax example in code (![alt](photo.jpg)), not a link
            return m.group(0)
        return m.group(1) + rebased + (f"#{anchor}" if anchor else "") + m.group(3)

    return LINK.sub(fix, text)


def render() -> str:
    out = ["# bobina — full documentation for agents\n\n"
           "> Generated by tools/gen_llms_full.py from the files below; the index is llms.txt.\n"]  # fmt: skip
    for rel in PARTS:
        out.append(f"\n\n<!-- file: {rel} -->\n\n")
        out.append(_rebase(_without((ROOT / rel).read_text(encoding="utf-8"), rel).strip(), rel) + "\n")
    return "".join(out)


if __name__ == "__main__":
    text = render()
    (ROOT / "llms-full.txt").write_text(text, encoding="utf-8")
    print(f"wrote llms-full.txt ({len(text) // 1024} KB)")
