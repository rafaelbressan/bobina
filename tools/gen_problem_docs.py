"""Regenerates, from nudges.CATALOG and problem_help.FIX: the 'Every problem, by stage' section of
docs/diagrams/nudges-flow.md, one page per code in docs/problems/, a page per category and the index (pages of removed
codes are deleted).
Run after adding or changing a code: python tools/gen_problem_docs.py (tests/test_docs.py and
tests/test_problem_help.py fail until the docs match). Never edit docs/problems/ by hand."""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from bobina.nudges import CATALOG  # noqa: E402
from bobina.problem_help import explain  # noqa: E402

STAGES = [
    ("Command line (errors: nothing prints)", ("E1",)),
    ("Input files and targets (errors)", ("E2",)),
    ("Data for batches (errors)", ("E3",)),
    ("Printer (errors)", ("E4",)),
    ("Document (errors)", ("E5",)),
    ("Chat with an AI (errors)", ("E6",)),
    ("Updates (errors)", ("E7",)),
    ("Template and data (security: always stop)", ("M3",)),
    ("Template and data (content)", ("M1", "M2")),
    ("Text and fonts", ("F",)),
    ("Layout and size", ("L",)),
    ("Codes (QR, barcodes, Pix)", ("Q",)),
    ("Images", ("I",)),
    ("Drawing", ("B",)),
    ("Charts and data= files", ("C",)),
    ("Paper and printer", ("P",)),
]


def main() -> None:
    p = ROOT / "docs" / "diagrams" / "nudges-flow.md"
    s = p.read_text(encoding="utf-8")
    head = s[: s.index("\n## Every problem, by stage")]
    out = [
        "\n## Every problem, by stage\n",
        "Generated by `tools/gen_problem_docs.py` from `src/bobina/nudges.py` (`bobina help nudges` lists the same).",
        "Errors stop the job and nothing prints; warnings and notes never do (except with `--strict`). Evidence = the",
        "printed test that measured the limit (`docs/printers/mtp-ii-58.md`). Every problem bobina reports has a code",
        "from this list.\n",
    ]
    for title, prefixes in STAGES:
        out.append(f"\n### {title}\n\n| Code | Severity | Meaning | Evidence |\n|---|---|---|---|")
        out += [f"| `{k}` | {sev} | {t} | {ev} |" for k, (sev, t, ev) in CATALOG.items() if k.startswith(prefixes)]
    p.write_text(head + "\n".join(out) + "\n", encoding="utf-8")
    write_pages()


def page(code: str) -> str:
    e = explain(code)
    lines = [f"# {e['code']}: {e['title']}", "", f"- Severity: {e['severity']}" + (
        " (stops the job: nothing prints)" if e["severity"] == "error" else " (never stops the job, except --strict)"),
        f"- Category: {e['category']}", ""]  # fmt: skip
    lines += ["## What to do", "", e["fix"], ""]
    if e["evidence"]:
        lines += [f"Evidence: printed test {e['evidence']} (docs/printers/mtp-ii-58.md).", ""]
    cat = e["category"]
    lines += [f"In the terminal: `bobina help {code}`. All {cat} codes and their meaning: "
              f"[{cat}]({cat.replace(' ', '-')}.md); every category: [index](README.md).", ""]  # fmt: skip
    return "\n".join(lines)


def write_pages() -> None:
    folder = ROOT / "docs" / "problems"
    folder.mkdir(exist_ok=True)
    keep = {"README", *(slug for slug, _, _ in categories())}
    for old in folder.glob("*.md"):  # a removed or renamed code must not keep its page
        if old.stem not in keep and old.stem not in CATALOG:
            old.unlink()
    for code in CATALOG:
        (folder / f"{code}.md").write_text(page(code), encoding="utf-8")
    for slug, _, _ in categories():
        (folder / f"{slug}.md").write_text(category_page(slug), encoding="utf-8")
    (folder / "README.md").write_text(index(), encoding="utf-8")


def categories() -> list[tuple[str, str, list[str]]]:
    """(page name, category, its codes) for each category, in the catalog's order."""
    from bobina.problem_help import CATEGORY

    found: dict[str, list[str]] = {}
    for code in CATALOG:
        found.setdefault(code[0], []).append(code)
    return [(CATEGORY[k].replace(" ", "-"), CATEGORY[k], codes) for k, codes in found.items()]


def category_page(slug: str) -> str:
    """One category's codes, a row each (the codes as plain link text, no backticks: the page stays short)."""
    _, name, codes = next(c for c in categories() if c[0] == slug)
    head = [
        f"# Problem codes: {name}",
        "",
        "Generated by `tools/gen_problem_docs.py`: one page per code, with what to do (`bobina help CODE`). Every "
        "category: [index](README.md).",
        "",
        "| Code | Severity | Meaning |",
        "|---|---|---|",
    ]
    rows = [f"| [{k}]({k}.md) | {CATALOG[k][0]} | {CATALOG[k][1]} |" for k in codes]
    return "\n".join([*head, *rows, ""])


def index() -> str:
    """The categories, each with a page of its codes and their meaning (category_page): one page with every code's
    meaning outgrew its token budget."""
    rows = [
        f"| [{name}]({slug}.md) | {' '.join(f'[{c}]({c}.md)' for c in codes)} |" for slug, name, codes in categories()
    ]
    head = [
        "# Problem codes",
        "",
        "Generated by `tools/gen_problem_docs.py`: one page per code, with what to do (`bobina help CODE`), and a page "
        "per category with each code's meaning. `bobina help nudges` lists them all in the terminal.",
        "",
        "| Category | Codes |",
        "|---|---|",
    ]
    return "\n".join([*head, *rows, ""])


if __name__ == "__main__":
    main()
